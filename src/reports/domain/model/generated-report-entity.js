export class GeneratedReportEntity {
    constructor({
                    id = null,
                    type = null,
                    month = null,
                    year = null,
                    start_date = null,
                    end_date = null,
                    sector_filter = null,
                    generation_date = null,
                    file_name = null,
                    status = null,
                    size_kb = null
                }) {
        this.id = id;
        this.type = type;
        this.month = month;
        this.year = year;
        this.start_date = start_date;
        this.end_date = end_date;
        this.sector_filter = sector_filter;
        this.generation_date = generation_date;
        this.file_name = file_name;
        this.status = status;
        this.size_kb = size_kb;
    }
}